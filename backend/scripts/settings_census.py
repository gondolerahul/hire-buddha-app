"""Write the money settings reference (Phase 15 T10-5): ``python scripts/settings_census.py [--write]``.

Every key of ``src.billing.settings_catalogue`` with its type, default, scopes
and meaning, grouped as the console groups them. ``tests/unit/test_settings_reference.py``
fails when a key is added or removed without regenerating the page.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.billing.settings_catalogue import CATALOGUE  # noqa: E402

OUT = Path(__file__).resolve().parents[2] / "docs" / "reference" / "money-settings.md"


def _default(spec) -> str:
    if spec.default is None:
        return "—"
    value = spec.default
    if isinstance(value, list):
        value = ", ".join(str(v) for v in value)
    return f"{value} {spec.unit}" if spec.unit and spec.unit not in ("%",) else f"{value}{spec.unit or ''}"


def render() -> str:
    groups: dict = {}
    for spec in CATALOGUE.values():
        groups.setdefault(spec.group, []).append(spec)
    lines = ["# Money settings", "",
             "> Generated by `backend/scripts/settings_census.py --write` from `src/billing/settings_catalogue.py`; "
             "do not edit by hand. Staff change these on **Console → Settings** (`/console/settings`) or with "
             "`PUT /api/v1/admin/billing-settings/{key}` and a reason; every change is in the admin audit log.",
             "", f"**{len(CATALOGUE)} settings** in {len(groups)} groups. *Scopes*: where a value may be set — "
             "the platform, a plan, a partner type, a partner or a company (the most specific wins).", ""]
    for group in sorted(groups):
        lines += [f"## {group}", "", "| Key | Type | Default | Scopes | Meaning |", "|---|---|---|---|---|"]
        for spec in sorted(groups[group], key=lambda s: s.key):
            kind = spec.type + (f" ({' / '.join(spec.choices)})" if spec.choices else "")
            meaning = spec.help.replace("|", "\\|")
            lines.append(f"| `{spec.key}` | {kind} | {_default(spec)} | {', '.join(spec.scopes)} | {meaning} |")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    text = render()
    if parser.parse_args().write:
        OUT.write_text(text, encoding="utf-8")
        print(f"wrote {len(CATALOGUE)} settings into {OUT}")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
