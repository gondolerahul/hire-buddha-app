"""
SQLAlchemy models for Artifact Management and Call Intelligence.

All files the system handles are tracked as Artifacts:
  - user-uploads: files manually uploaded by users
  - system-generated: files created by AI agents/tools

The bytes are kept by the storage adapter (src/common/platform/storage) under
``storage_key`` — ``c-<company>/<artifacts|uploads|recordings>/<date>/<name>``
for new files (Phase 14 WS1 1.2). Rows from before it keep the key of their
file under backend/artifact (``<origin>/<company_id>/<date>/<name>``).
"""
import uuid
from datetime import datetime
from sqlalchemy import (
    Column, String, Text, Integer, Boolean, DateTime, ForeignKey,
    Numeric, BigInteger, Index
)
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import relationship
from src.common.tenancy.bases import TenantBase, refers_to
from src.ai.orm import HierarchicalEntity, ExecutionRun


class Artifact(TenantBase):
    """
    Tracks every file the platform saves — whether uploaded by a user or
    generated by an AI agent / tool.

    Read the bytes through ``src.ai.artifact_service`` (``read_artifact_bytes``,
    ``artifact_local_file``), never through ``file_path``: on Azure there is no
    local file.
    """
    __tablename__ = "artifacts"
    __table_args__ = (
        Index("idx_artifacts_company", "company_id"),
        Index("idx_artifacts_campaign", "campaign_id"),
        Index("idx_artifacts_agent", "agent_id"),
        Index("idx_artifacts_origin", "origin"),
        Index("idx_artifacts_file_category", "file_category"),
        Index("idx_artifacts_created_at", "created_at"),
    )

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    company_id = Column(UUID(as_uuid=True), nullable=False, info=refers_to("companies.id"))
    # The campaign this file belongs to (DM-18: the key pointed at hierarchical_entities).
    campaign_id = Column(UUID(as_uuid=True), ForeignKey("campaigns.id", ondelete="SET NULL"), nullable=True)
    agent_id = Column(UUID(as_uuid=True), ForeignKey("hierarchical_entities.id"), nullable=True)
    run_id = Column(UUID(as_uuid=True), ForeignKey("execution_runs.id"), nullable=True)

    # Origin: who produced this file
    origin = Column(String(30), nullable=False)        # user-uploads | system-generated

    # What kind of content this is
    file_category = Column(String(50), nullable=False) # recordings | images | videos | documents | text
    file_name = Column(String(500), nullable=False)
    # The local file on local-disk storage, else the storage key; a provider
    # URL for a call recording kept at the provider. What a tool shows the model.
    file_path = Column(Text(), nullable=False)
    # Where the bytes are: a neutral key for the storage adapter (P-05). NULL
    # for a provider URL, or a file from before storage keys outside backend/artifact.
    storage_key = Column(Text(), nullable=True)
    file_size = Column(BigInteger, nullable=True)       # bytes
    duration_seconds = Column(Integer, nullable=True)  # For audio/video
    mime_type = Column(String(100), nullable=True)

    # Provenance — why was this created and by what
    purpose = Column(Text, nullable=True)              # Human-readable description
    generated_by = Column(String(200), nullable=True)  # Tool / agent / process name (e.g. 'image_generation', 'pdf_generator')

    artifact_metadata = Column(JSONB, nullable=True)    # Extra info (dimensions, call SID, model used, etc.)

    created_at = Column(DateTime(timezone=True), default=datetime.utcnow, nullable=False)

    # Relationships
    agent = relationship("HierarchicalEntity", foreign_keys=[agent_id])
    run = relationship("ExecutionRun")

    # Back-reference from call_content
    call_contents = relationship("CallContent", back_populates="audio_artifact")


class CallLog(TenantBase):
    """
    Telephony call metadata for call intelligence and reporting.
    """
    __tablename__ = "call_logs"
    __table_args__ = (
        Index("idx_call_logs_company", "company_id"),
        Index("idx_call_logs_agent", "agent_id"),
        Index("idx_call_logs_created_at", "created_at"),
    )

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    company_id = Column(UUID(as_uuid=True), nullable=False, info=refers_to("companies.id"))
    voice_session_id = Column(UUID(as_uuid=True), nullable=True)   # Ref to voice_sessions (no FK: different module)
    agent_id = Column(UUID(as_uuid=True), ForeignKey("hierarchical_entities.id"), nullable=True)

    direction = Column(String(20), nullable=True)       # inbound | outbound
    status = Column(String(30), nullable=True)          # completed | failed | no-answer
    duration_seconds = Column(Integer, nullable=True)
    from_number = Column(String(30), nullable=True)
    to_number = Column(String(30), nullable=True)
    provider = Column(String(30), nullable=True)        # twilio | tata_tele
    call_cost_usd = Column(Numeric(24, 10), nullable=True)

    created_at = Column(DateTime(timezone=True), default=datetime.utcnow, nullable=False)

    # Relationships
    agent = relationship("HierarchicalEntity")
    content = relationship("CallContent", back_populates="call_log", uselist=False)


class CallContent(TenantBase):
    """
    Transcript and summary for a call, with a reference to the audio recording artifact.
    """
    __tablename__ = "call_content"
    __table_args__ = (Index("idx_call_content_call_log", "call_log_id"),)

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    call_log_id = Column(UUID(as_uuid=True), ForeignKey("call_logs.id"), nullable=False)
    audio_artifact_id = Column(UUID(as_uuid=True), ForeignKey("artifacts.id"), nullable=True)

    transcript_text = Column(Text, nullable=True)
    summary_text = Column(Text, nullable=True)
    sentiment = Column(String(20), nullable=True)    # positive | neutral | negative
    content_metadata = Column(JSONB, nullable=True)

    created_at = Column(DateTime(timezone=True), default=datetime.utcnow, nullable=False)

    # Relationships
    call_log = relationship("CallLog", back_populates="content")
    audio_artifact = relationship("Artifact", back_populates="call_contents")
